#!/usr/bin/env bash
# Builds a debug .prg that launches straight into one screen with canned
# race data (source/Debug/DebugLaunch.mc), for simulator screenshots.
#
# Usage: tools/screenshots/shoot.sh <screen> <device> <out.prg>
#   screen: home | home_unpaired | home_searching | division | roxzone |
#           custom | custom_empty | run | run_long | roxzone_active |
#           station | station_heavy | last | paused | menu | menu_paused |
#           finished | result | result_early | splits
#           tour  — every screen above in turn, 4 s each; prints
#                   "SHOT <screen>" as each one appears
#
# Env: SDK_PATH (default: current SDK), CIQ_KEY (default: developer_key.der)
# Then:  "$SDK_PATH/bin/monkeydo" <out.prg> <device>
#
# Release builds never contain this path — (:debug) code is stripped by -r.

set -euo pipefail

SCREEN="${1:?screen}"
DEVICE="${2:?device}"
OUT="${3:?output .prg}"
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
SDK_PATH="${SDK_PATH:-$(sed 's:/*$::' "$HOME/Library/Application Support/Garmin/ConnectIQ/current-sdk.cfg")}"
KEY="${CIQ_KEY:-$ROOT/developer_key.der}"

if ! /usr/libexec/java_home >/dev/null 2>&1; then
    for candidate in /opt/homebrew/opt/openjdk@17 /opt/homebrew/opt/openjdk; do
        if [[ -x "$candidate/bin/java" ]]; then
            export JAVA_HOME="$candidate/libexec/openjdk.jdk/Contents/Home"
            export PATH="$candidate/bin:$PATH"
            break
        fi
    done
fi

mkdir -p "$HERE/gen"
cat > "$HERE/gen/DebugScreen.mc" <<EOF
import Toybox.Lang;

// Generated by tools/screenshots/shoot.sh — not committed.
(:debug)
module DebugScreen {
    function id() as String? { return "$SCREEN"; }
}
EOF

"$SDK_PATH/bin/monkeyc" \
    --jungles "$HERE/shots.jungle" \
    --device "$DEVICE" \
    --output "$OUT" \
    --private-key "$KEY" \
    --warn
